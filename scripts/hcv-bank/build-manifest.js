#!/usr/bin/env node
/**
 * Regenerate manifest.json and INDEX.md from the chapter files.
 * Run after adding or editing any chapter file.
 *
 * usage: node scripts/hcv-bank/build-manifest.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..', '_agents', 'question-banks', 'physics-hcv');
const DIR = path.join(ROOT, 'chapters');

const files = fs.readdirSync(DIR).filter(f => f.endsWith('.json')).sort();
const rows = files.map(f => {
  const d = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
  const pb = d.blocks.practice_bank;
  const mcqs = pb.sections.reduce((s, x) => s + x.items.filter(i => i.kind === 'mcq').length, 0);
  const numericals = pb.sections.reduce((s, x) => s + x.items.filter(i => i.kind === 'numerical').length, 0);
  return {
    file: f,
    hcv_chapter: d.hcv_chapter,
    hcv_title: d.hcv_title,
    ncert_class: d.ncert.class,
    ncert_chapter_hint: d.ncert.chapter_hint,
    practice_bank_id: pb.id,
    sections: pb.sections.map(s => ({ id: s.id, title: s.title, items: s.items.length })),
    mcqs, numericals,
    worked_examples: d.blocks.worked_examples.length,
    worked_example_ids: d.blocks.worked_examples.map(w => w.id),
    notes: d.notes || '',
  };
});

const totals = {
  chapters: rows.length,
  mcqs: rows.reduce((s, r) => s + r.mcqs, 0),
  numericals: rows.reduce((s, r) => s + r.numericals, 0),
  worked_examples: rows.reduce((s, r) => s + r.worked_examples, 0),
};

fs.writeFileSync(path.join(ROOT, 'manifest.json'),
  JSON.stringify({ generated_from: 'chapters/*.json', totals, chapters: rows }, null, 1) + '\n');

// ── INDEX.md, grouped by NCERT target so a page-builder can find its bank fast ──
const byClass = { 11: [], 12: [], other: [] };
for (const r of rows) (byClass[r.ncert_class] || byClass.other).push(r);

let md = `# Physics practice corpus — index

Auto-generated by \`node scripts/hcv-bank/build-manifest.js\`. Do not edit by hand.

**${totals.chapters} chapters · ${totals.mcqs} MCQs · ${totals.worked_examples} worked examples**

Every chapter file holds two ready-to-insert payloads:
- one \`practice_bank\` block (sectioned MCQs) — drop at the end of a chapter
- an array of \`worked_example\` blocks — drop inline beside the relevant concept

Insert with \`node scripts/hcv-bank/insert-blocks.js --chapter <n> --page <slug> --what bank|worked|all\`.
Add \`--dry\` first to preview. See README.md for the full flow.

`;

for (const cls of ['11', '12', 'other']) {
  const list = byClass[cls];
  if (!list.length) continue;
  md += `\n## ${cls === 'other' ? 'Unmapped / enrichment' : 'Class ' + cls} \n\n`;
  md += `| Ch | Title | NCERT target | MCQ | WE | Sections |\n|---:|---|---|---:|---:|---|\n`;
  for (const r of list) {
    md += `| ${r.hcv_chapter} | ${r.hcv_title} | ${r.ncert_chapter_hint} | ${r.mcqs} | ${r.worked_examples} | ${r.sections.map(s => `\`${s.id}\` (${s.items})`).join('<br>')} |\n`;
  }
}

md += `\n## Chapters carrying a caveat\n\n`;
const caveats = rows.filter(r => /SYLLABUS FLAG|corrupt|no Worked Out Examples|OUTSIDE/i.test(r.notes));
if (caveats.length) {
  for (const r of caveats) md += `- **Ch ${r.hcv_chapter} ${r.hcv_title}** — ${r.notes}\n`;
} else md += `_none_\n`;

fs.writeFileSync(path.join(ROOT, 'INDEX.md'), md);

console.log(`manifest.json + INDEX.md written`);
console.log(`  ${totals.chapters} chapters, ${totals.mcqs} MCQs, ${totals.worked_examples} worked examples`);
